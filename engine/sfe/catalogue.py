"""Rule and source validation, catalogue pages, checklists and Semgrep export."""
from __future__ import annotations

import re

import yaml

from .config import Config
from .patterns import compile_pattern


# --------------------------------------------------------------------------- validation
def validate_rule(cfg: Config, r, sources, origin, err, repo_checks=(), manifest_checks=()):
    rid = r.get("id", "?")
    for k in cfg.required_fields:
        if k not in r:
            err(f"{origin} {rid}: missing field '{k}'")
    if not cfg.id_re.match(rid):
        err(f"{origin} {rid}: id does not match PREFIX-AREA-NN")
    if r.get("level") not in ("MUST", "SHOULD"):
        err(f"{origin} {rid}: level must be MUST or SHOULD")
    if r.get("tier") not in (1, 2, 3):
        err(f"{origin} {rid}: tier must be 1, 2 or 3")
    if not set(r.get("profiles", [])) <= cfg.profiles:
        err(f"{origin} {rid}: unknown profile in {r.get('profiles')}")
    dims = r.get(cfg.dimension_key, [])
    if dims != ["all"] and not set(dims) <= set(cfg.dimension_values):
        err(f"{origin} {rid}: unknown {cfg.dimension_label.lower()[:-1] if cfg.dimension_label.endswith('s') else cfg.dimension_label.lower()} in {dims}")
    if not set(r.get("features", []) or []) <= cfg.features:
        err(f"{origin} {rid}: unknown feature in {r.get('features')}")
    if r.get("effort") not in ("low", "medium", "high"):
        err(f"{origin} {rid}: effort must be low, medium or high")
    types = set()
    for sid in r.get("sources", []):
        if sid not in sources:
            err(f"{origin} {rid}: unknown source '{sid}'")
        else:
            types.add(sources[sid].get("type"))
    tier = r.get("tier")
    if tier in cfg.tier_min_types and types and not (types & cfg.tier_min_types[tier]):
        err(f"{origin} {rid}: tier {tier} needs at least one source of type {sorted(cfg.tier_min_types[tier])}")
    det = r.get("detection") or {}
    if det.get("method") not in ("static", "manifest", "manual", "mixed"):
        err(f"{origin} {rid}: detection.method invalid")
    for p in det.get("patterns", []) or []:
        validate_pattern(p, f"{origin} {rid}", err, repo_checks, manifest_checks)


def validate_pattern(p, where, err, repo_checks=(), manifest_checks=()):
    t = p.get("type")
    if t == "regex":
        try:
            compile_pattern(p)
        except re.error as e:
            err(f"{where}: bad regex: {e}")
    elif t == "dependency":
        if not p.get("names"):
            err(f"{where}: dependency pattern without names")
    elif t == "repo":
        if p.get("check") not in repo_checks:
            err(f"{where}: unknown repo check {p.get('check')}")
    elif t == "manifest":
        if p.get("check") not in manifest_checks:
            err(f"{where}: unknown manifest check {p.get('check')}")
    else:
        err(f"{where}: unknown pattern type {t}")
    if p.get("confidence", "medium") not in ("high", "medium"):
        err(f"{where}: confidence must be high or medium")


def validate_sources(cfg: Config, sources, origin, err):
    for sid, s in sources.items():
        for k in cfg.source_required:
            if k not in s:
                err(f"{origin} source {sid}: missing '{k}'")
        if s.get("type") not in cfg.source_types:
            err(f"{origin} source {sid}: unknown type {s.get('type')}")


# --------------------------------------------------------------------------- generation
def header(cfg: Config) -> str:
    return f"<!-- GENERATED by {cfg.generator} from framework/rules.yaml. Do not edit by hand. -->\n\n"


def dimension_txt(cfg: Config, r):
    b = r.get(cfg.dimension_key, ["all"])
    return "all" if b == ["all"] else ", ".join(f"{x} ({cfg.dimension_values[x]})" for x in b)


def src_links(r, sources):
    out = []
    for sid in r.get("sources", []):
        s = sources.get(sid, {})
        out.append(f"[{sid}]({s['url']})" if s.get("url") else sid)
    return ", ".join(out)


def rule_block(cfg: Config, r, sources):
    lines = [f"### {r['id']}: {r['title']}", ""]
    lines.append(f"**{r['level']}** · Level {r['tier']} ({cfg.levels[r['tier']]}) · {cfg.dimension_label}: {dimension_txt(cfg, r)}"
                 + (f" · Features: {', '.join(r['features'])}" if r.get("features") else "")
                 + f" · Detection: {(r.get('detection') or {}).get('method', 'manual')} · Effort: {r.get('effort')}")
    lines += ["", f"**Requirement.** {r['requirement'].strip()}", "",
              f"**Why.** {r['rationale'].strip()}", "",
              f"**How to improve.** {r['improvement'].strip()}", ""]
    for n in r.get("notes", []):
        lines += [f"**National note.** {n}", ""]
    lines += [f"**Sources.** {src_links(r, sources)}", ""]
    return lines


def anchor(r):
    return re.sub(r"[^a-z0-9 -]", "", f"{r['id']}: {r['title']}".lower()).replace(" ", "-")


def catalogue_page(cfg: Config, title, intro, rules, sources):
    lines = [header(cfg) + f"# {title}", "", intro, "",
             "| ID | Rule | Strength | Level | Detection |", "|---|---|---|---|---|"]
    for r in rules:
        lines.append(f"| [{r['id']}](#{anchor(r)}) | {r['title']} | {r['level']} | {r['tier']} | {(r.get('detection') or {}).get('method')} |")
    lines.append("")
    for r in rules:
        lines += rule_block(cfg, r, sources)
    return "\n".join(lines)


def checklist_page(cfg: Config, title, rules):
    lines = [header(cfg) + f"# Self-assessment: {title}", "",
             "Tick each item you can evidence. Keep the evidence (link, file, screenshot) next to the tick.",
             "Pick your target level: complete every item of that level and of the levels below it.", "",
             "Product: ____________________  Date: __________  Assessor: ____________________", ""]
    for t in (1, 2, 3):
        sub = [r for r in rules if r["tier"] == t]
        if not sub:
            continue
        lines += [f"## Level {t}: {cfg.levels[t]}", ""]
        for r in sub:
            lines.append(f"- [ ] **{r['id']}** ({r['level']}) {r['title']}. {r['requirement'].strip()}  ")
            lines.append(f"      Evidence: ")
        lines.append("")
    return "\n".join(lines)


def semgrep_yaml(cfg: Config, rules):
    out = []
    for r in rules:
        for i, p in enumerate((r.get("detection") or {}).get("patterns", []) or []):
            if p["type"] != "regex":
                continue
            rx = p["pattern"]
            if "i" in str(p.get("flags", "")):
                rx = "(?i)" + rx
            sev = "ERROR" if (r["level"] == "MUST" and p.get("confidence") == "high") else "WARNING" if r["level"] == "MUST" else "INFO"
            entry = {
                "id": f"{r['id']}-{i + 1}".lower(),
                "message": f"{r['id']} ({r['level']}, level {r['tier']}): {r['title']}. {r['improvement'].strip()}",
                "severity": sev,
                "languages": ["generic"],
                "pattern-regex": rx,
                "metadata": {cfg.rule_meta_key: r["id"], "tier": r["tier"], "sources": r["sources"]},
            }
            if p.get("globs"):
                entry["paths"] = {"include": p["globs"]}
            out.append(entry)
    return f"# GENERATED by {cfg.generator}. Do not edit by hand.\n" + yaml.safe_dump({"rules": out}, sort_keys=False, allow_unicode=True, width=200)
